import { expect, test } from '@playwright/test'
import { DriveFixture } from './fixtures'
import { samplePackage } from '../src/lab/fixtures.test-support'

test('SQL study preserves the draft and caret through a long case and the expanded editor', async ({ page, context, browserName }) => {
  test.setTimeout(90_000)
  const pack = samplePackage()
  pack.objectives[0].topicId = 'III.1'
  const prompt = [
    'Obtén el número de registros.',
    ...Array.from({ length: 18 }, (_, index) => `Registro ${index + 1} de inventario. La tabla contiene valores que se revisan cada día.`),
  ].join('\n\n')
  const setup = 'CREATE TABLE demo(n integer); INSERT INTO demo VALUES (1),(2);'
  pack.activities[0] = { ...pack.activities[0], kind: 'sql', prompt, starter: 'SELECT COUNT(*) FROM demo',
    referenceQuery: 'SELECT COUNT(*) FROM demo', comparison: 'ordered',
    datasets: [{ id: 'first', setup }, { id: 'second', setup }] }
  const drive = new DriveFixture()
  drive.addLabPackage('lab-editor', pack)
  await drive.install(context, browserName === 'webkit')

  await page.goto('/tai-hub/')
  await page.getByRole('button', { name: 'Conectar Google Drive', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Continuar estudio' })).toBeVisible()
  const lab = page.getByRole('button', { name: 'Laboratorio TAI', exact: true })
  if (!await lab.isVisible()) await page.getByRole('button', { name: 'Abrir navegación', exact: true }).click()
  await lab.click()
  await page.getByRole('button', { name: 'Cargar lecciones de Drive' }).click()
  await page.getByRole('button', { name: /^III\.1 .*Modelado.*0 de 1 lecciones/ }).click()
  await page.getByRole('button', { name: /Lección sintética/ }).click()
  await page.getByRole('button', { name: 'Practicar', exact: true }).click()

  const editor = page.getByRole('textbox', { name: 'Consulta SQL', exact: true })
  const query = 'SELECT COUNT(*)\nFROM demo'
  await editor.fill(query)
  await editor.evaluate(node => (node as HTMLTextAreaElement).setSelectionRange(3, 8))
  const caseTrigger = page.getByRole('button', { name: 'Ver caso', exact: true })
  await caseTrigger.click()
  const caseDialog = page.getByRole('dialog', { name: 'Enunciado del caso' })
  await expect(caseDialog).toBeVisible()
  expect(await caseDialog.evaluate(node => node.contains(document.activeElement))).toBe(true)
  const caseText = caseDialog.getByRole('region', { name: 'Texto del caso' })
  await caseText.evaluate(node => { node.scrollTop = 240 })
  await expect.poll(() => caseText.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  const caseScroll = await caseText.evaluate(node => node.scrollTop)
  await caseDialog.getByRole('button', { name: 'Volver a la pregunta' }).click()
  await expect(caseTrigger).toBeFocused()
  await expect(editor).toHaveValue(query)
  await caseTrigger.click()
  await expect.poll(() => caseText.evaluate(node => node.scrollTop)).toBe(caseScroll)
  await caseDialog.getByRole('button', { name: 'Volver a la pregunta' }).click()

  const expand = page.getByRole('button', { name: 'Ampliar editor', exact: true })
  await expand.click()
  const expanded = page.getByRole('dialog', { name: 'Editor SQL' })
  await expect(expanded).toBeVisible()
  await expect(editor).toBeFocused()
  expect(await editor.evaluate(node => [(node as HTMLTextAreaElement).selectionStart, (node as HTMLTextAreaElement).selectionEnd]))
    .toEqual([3, 8])
  await expanded.getByText('Ver enunciado', { exact: true }).click()
  await expect(expanded.getByText('Obtén el número de registros.', { exact: true })).toBeVisible()
  await expanded.getByRole('button', { name: 'Volver a la actividad' }).click()
  await expect(expand).toBeFocused()
  await expect(editor).toHaveValue(query)
  const historyLength = await page.evaluate(() => history.length)
  await page.getByRole('button', { name: 'Ejecutar SQL' }).click()
  await expect(page.getByRole('cell', { name: '2', exact: true })).toBeVisible({ timeout: 25_000 })
  await page.getByRole('button', { name: 'Comprobar SQL' }).click()
  await expect(page.getByText('Correcta en los casos comprobados.', { exact: true })).toBeVisible({ timeout: 30_000 })
  expect(await page.evaluate(() => history.length)).toBe(historyLength)
  await page.getByRole('button', { name: 'Volver al tema', exact: true }).click()
  await expect(page.getByRole('button', { name: /Lección sintética/ })).toBeVisible()
})

test('reading resumes at its saved position and switching stages preserves the selected answer and correction', async ({ page, context, browserName }) => {
  const pack = samplePackage()
  pack.objectives[0].topicId = 'III.1'
  pack.lessons[0].explanation[0].body = Array.from({ length: 24 }, (_, i) =>
    `Párrafo ${i + 1}. La regla se comprueba con un ejemplo y se aplica a los datos del caso.`).join('\n\n')
  const drive = new DriveFixture()
  drive.addLabPackage('lab-resume-reading', pack)
  await drive.install(context, browserName === 'webkit')
  await page.goto('/tai-hub/')
  await page.getByRole('button', { name: 'Conectar Google Drive', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Continuar estudio' })).toBeVisible()
  const lab = page.getByRole('button', { name: 'Laboratorio TAI', exact: true })
  const mobileLab = page.getByRole('button', { name: 'Abrir Laboratorio TAI' })
  await (await mobileLab.isVisible() ? mobileLab : lab).click()
  await page.getByRole('button', { name: 'Cargar lecciones de Drive' }).click()
  const topic = page.getByRole('button', { name: /^III\.1 .*Modelado.*0 de 1 lecciones/ })
  await topic.click()
  await page.getByRole('button', { name: /Lección sintética/ }).click()
  await expect(page.getByText(/^Párrafo 24\./)).toBeVisible()
  await page.evaluate(() => window.scrollTo({ top: 520, behavior: 'instant' }))
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(520)
  await page.getByRole('button', { name: 'Volver al tema', exact: true }).evaluate(button => (button as HTMLButtonElement).click())
  await page.goBack()
  await page.getByRole('button', { name: 'Continuar lectura', exact: true }).click()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(520)
  const practice = page.getByRole('button', { name: 'Practicar', exact: true })
  const option = page.getByRole('radio', { name: 'Válida', exact: true })
  await practice.click()
  await option.check()
  await page.getByRole('button', { name: 'Leer', exact: true }).click()
  await practice.click()
  await expect(option).toBeChecked()
  const check = page.getByRole('button', { name: 'Comprobar respuesta', exact: true })
  await expect(check).toBeEnabled()
  await check.press('Enter')
  await expect(page.getByText('Respuesta correcta', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Siguiente actividad', exact: true }).click()
  await page.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(option).toBeChecked()
  await expect(page.getByText('Respuesta correcta', { exact: true })).toBeVisible()
})
